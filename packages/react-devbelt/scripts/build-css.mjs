// Compiles the toolbar's Tailwind CSS once, at build time, so users need no
// Tailwind setup. Output:
//   dist/styles.css                 the full stylesheet (for isolation="none")
//   src/ui/styles.generated.ts      { props, css } strings for the shadow root
//
// Tailwind v4 declares its --tw-* variables with `@property`, and browsers
// ignore `@property` inside a shadow tree. They must be registered on the
// document, so they are split out here and injected into <head> at runtime.
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const input = resolve(root, "src/ui/styles.css");
const out = resolve(root, "dist/styles.css");
mkdirSync(dirname(out), { recursive: true });

execFileSync(
  resolve(root, "node_modules/.bin/tailwindcss"),
  ["-i", input, "-o", out, "--minify"],
  { stdio: "inherit", cwd: root },
);

const css = readFileSync(out, "utf8");

// Pull every top-level `@property --x{...}` rule out of the stylesheet.
const props = [];
let main = "";
for (let i = 0; i < css.length; ) {
  if (css.startsWith("@property", i)) {
    const open = css.indexOf("{", i);
    let depth = 0;
    let j = open;
    for (; j < css.length; j++) {
      if (css[j] === "{") depth++;
      else if (css[j] === "}" && --depth === 0) break;
    }
    props.push(css.slice(i, j + 1));
    i = j + 1;
  } else {
    main += css[i++];
  }
}

const generated = `// Generated by scripts/build-css.mjs. Do not edit.
export const PROPERTY_CSS = ${JSON.stringify(props.join(""))};
export const TOOLBAR_CSS = ${JSON.stringify(main)};
`;
writeFileSync(resolve(root, "src/ui/styles.generated.ts"), generated);
console.log(`styles: ${props.length} @property rules, ${(main.length / 1024).toFixed(1)} kB css`);
